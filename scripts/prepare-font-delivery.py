"""Build lossless gzip PDF fonts and small browser-only sample faces.

Requires the same fontTools installation as setup-fonts.py. Original static TTFs
are never modified; gzip outputs must decompress to their exact SHA-256.
"""
from __future__ import annotations

import gzip
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.tools' / 'font-python'))
from fontTools import subset
from fontTools.ttLib import TTFont

FONTS = ROOT / 'public' / 'fonts'
SAMPLE = '让经历清晰呈现专业技能工作经历 · Resume & Portfolio'
POINTS = sorted(set(range(32, 127)) | {ord(character) for character in SAMPLE})


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def prepare(selected: list[str] | None = None) -> None:
    manifest_path = FONTS / 'manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    (FONTS / 'compressed').mkdir(exist_ok=True)
    (FONTS / 'samples').mkdir(exist_ok=True)
    css = ['/* Generated by prepare-font-delivery.py. Only the fixed settings sample uses these subsets; PDFs use complete TTFs. */']
    report = []
    if selected and any(key not in manifest['families'] for key in selected):
        raise ValueError('Unknown selected font family')
    for family_id, family in manifest['families'].items():
        if selected and family_id not in selected:
            continue
        for file in family['files']:
            original = (FONTS / file['file']).read_bytes()
            sha = digest(original)
            if sha != file['sha256']:
                raise ValueError('Original font checksum mismatch: ' + file['file'])
            # Keep a font MIME type and avoid HTTP .gz auto-decoding. This private
            # delivery path contains gzip bytes, consumed only by our loader.
            compressed_name = f"compressed/{Path(file['file']).stem}.{sha[:16]}.ttf"
            compressed_path = FONTS / compressed_name
            previous_path = FONTS / file.get('compressed', {}).get('file', '')
            packed = compressed_path.read_bytes() if compressed_path.exists() else previous_path.read_bytes() if previous_path.is_file() else gzip.compress(original, compresslevel=9, mtime=0)
            if gzip.decompress(packed) != original:
                raise ValueError('Gzip font round-trip mismatch: ' + file['file'])
            if not compressed_path.exists():
                compressed_path.write_bytes(packed)
            if len(packed) >= 25 * 1024 * 1024:
                raise ValueError('Compressed font exceeds Cloudflare static asset limit')
            file['compressed'] = {'file': compressed_name, 'sha256': digest(packed), 'bytes': len(packed), 'originalBytes': len(original)}
            if file['style'] == 'normal':
                sample_key = digest((sha + ':' + ','.join(map(str, POINTS))).encode())[:16]
                preview_name = f"samples/{Path(file['file']).stem}.{sample_key}.woff"
                preview_path = FONTS / preview_name
                if not preview_path.exists():
                    font = TTFont(FONTS / file['file'])
                    options = subset.Options()
                    options.layout_features = ['*']
                    subsetter = subset.Subsetter(options=options)
                    subsetter.populate(unicodes=POINTS)
                    subsetter.subset(font)
                    font.flavor = 'woff'
                    font.save(preview_path)
                    font.close()
                preview = preview_path.read_bytes()
                sample_font = TTFont(preview_path)
                if not set(POINTS).issubset(sample_font.getBestCmap()):
                    raise ValueError('Sample font lost displayed characters')
                sample_font.close()
                unicode_range = ','.join(f'U+{point:X}' for point in POINTS)
                file['preview'] = {'file': preview_name, 'sha256': digest(preview), 'bytes': len(preview), 'unicodeRange': unicode_range}
            print(f"{file['file']}: {len(original):,} -> {len(packed):,} bytes", flush=True)
    # Refresh the complete CSS/catalog from metadata without rereading or
    # regenerating unrelated families when --family limits the work above.
    for family in manifest['families'].values():
        for file in family['files']:
            packed = file['compressed']
            preview = file.get('preview')
            if file['style'] == 'normal':
                if not preview:
                    raise ValueError('Missing sample metadata: ' + file['file'])
                css.append(f"@font-face{{font-family:{family['family']};src:url('/fonts/{preview['file']}') format('woff');font-weight:{file['weight']};font-style:normal;font-display:swap;unicode-range:{preview['unicodeRange']}}}")
            report.append({'file': file['file'], 'originalBytes': packed['originalBytes'], 'compressedBytes': packed['bytes'], 'sampleBytes': preview['bytes'] if preview else 0})
    manifest['version'] = max(manifest['version'], 7)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'src' / 'features' / 'appearance' / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
    output = ROOT / 'output' / 'font-performance'
    output.mkdir(parents=True, exist_ok=True)
    (output / 'delivery-report.json').write_text(json.dumps(report, indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--family', action='append', help='Prepare only this family; preserve other verified delivery assets')
    args = parser.parse_args()
    prepare(args.family)
