// Run against a synthetic local resume in an isolated browser session.
async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 980 });
  await page.getByRole('button', { name: '页面设置', exact: true }).click();
  const more = page.locator('summary[aria-label="更多排版设置"]');
  const avatar = page.locator('summary[aria-label="头像外观"]');
  const moreDetails = page.locator('.appearance-disclosure').filter({ has: more });
  const avatarDetails = page.locator('.appearance-disclosure').filter({ has: avatar });
  assert(await moreDetails.evaluate(element => !element.open), 'Advanced layout should initially be collapsed');
  assert(await avatarDetails.evaluate(element => !element.open), 'Avatar details should initially be collapsed');
  assert(await page.getByRole('combobox', { name: '简历字体', exact: true }).isVisible(), 'Font choice is hidden');
  assert(await page.getByRole('spinbutton', { name: '字体大小数值', exact: true }).isVisible(), 'Body font size is hidden');
  assert(await page.getByRole('spinbutton', { name: '行高数值', exact: true }).isVisible(), 'Line height is hidden');
  await more.focus(); await page.keyboard.press('Enter');
  assert(await moreDetails.evaluate(element => element.open), 'Enter did not expand advanced layout');
  const margin = page.getByRole('spinbutton', { name: '外边距数值', exact: true });
  const originalMargin = await margin.inputValue();
  const nextMargin = originalMargin === '23' ? '24' : '23';
  await margin.fill(nextMargin); await margin.press('Tab');
  assert(await moreDetails.evaluate(element => element.open), 'Editing a setting collapsed the disclosure');
  assert((await more.textContent()).includes(`边距 ${nextMargin}px`), 'Collapsed summary does not track current settings');
  const pageNumbers = page.getByRole('switch', { name: '显示页码', exact: true });
  const originalPageNumbers = await pageNumbers.getAttribute('aria-checked');
  await pageNumbers.click();
  await more.focus(); await page.keyboard.press('Space');
  assert(await moreDetails.evaluate(element => !element.open), 'Space did not collapse advanced layout');
  assert(await margin.isHidden(), 'Collapsed setting remains visible');
  assert(await more.evaluate(element => element === document.activeElement), 'Collapse did not keep keyboard focus on summary');
  await page.keyboard.press('Tab');
  assert(await avatar.evaluate(element => element === document.activeElement), 'Tab entered hidden advanced fields');
  await page.keyboard.press('Enter');
  assert(await avatarDetails.evaluate(element => element.open), 'Enter did not expand avatar appearance');
  const width = page.getByRole('spinbutton', { name: '头像大小数值', exact: true });
  const originalWidth = await width.inputValue(), nextWidth = originalWidth === '93' ? '94' : '93';
  await width.fill(nextWidth); await width.press('Tab');
  await avatar.focus(); await page.keyboard.press('Space');
  assert((await avatar.textContent()).includes(`${nextWidth} ×`), 'Avatar summary does not reflect width');
  await more.click();
  assert(await margin.inputValue() === nextMargin, 'Closing disclosure reset margin');
  assert(await pageNumbers.getAttribute('aria-checked') !== originalPageNumbers, 'Closing disclosure reset page numbers');
  await margin.fill(originalMargin); await margin.press('Tab'); await pageNumbers.click();
  await avatar.click();
  assert(await width.inputValue() === nextWidth, 'Closing disclosure reset avatar width');
  await width.fill(originalWidth); await width.press('Tab');
  await more.click(); await avatar.click();
  await page.setViewportSize({ width: 375, height: 812 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Appearance layout overflows narrow viewport');
  await more.focus(); await page.keyboard.press('Enter');
  assert(await margin.isVisible(), 'Advanced settings unavailable on mobile');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Expanded appearance layout overflows narrow viewport');
  await more.focus(); await page.keyboard.press('Space');
  await page.setViewportSize({ width: 1440, height: 980 });
  return { commonSettingsVisible: true, disclosureKeyboard: true, hiddenFieldsSkipped: true, valuesRetained: true, summariesUpdated: true, mobileOverflow: false };
}
