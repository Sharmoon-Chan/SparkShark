async (page) => {
  const report = [];
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.reload();
  const name = page.getByRole('textbox', { name: '全名', exact: true });
  await name.waitFor();
  await page.evaluate(() => {
    window.__myresumeTestPut = IDBObjectStore.prototype.put;
    IDBObjectStore.prototype.put = function(...args) { if (this.name === 'resumes') throw new DOMException('Simulated storage quota', 'QuotaExceededError'); return window.__myresumeTestPut.apply(this, args); };
  });
  await name.fill('未保存内容测试');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.save-indicator.failed'));
  if (await name.inputValue() !== '未保存内容测试') throw new Error('Storage failure erased the draft');
  await page.getByRole('button', { name: '导出与备份', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.locator('.panel-content').getByRole('button', { name: '下载 JSON 备份', exact: true }).click();
  const download = await downloadEvent; await download.saveAs('output/playwright/unsaved-backup.json');
  await page.evaluate(() => { IDBObjectStore.prototype.put = window.__myresumeTestPut; delete window.__myresumeTestPut; });
  await page.getByRole('button', { name: '重试保存', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.save-indicator.saved'));
  report.push('保存失败保留草稿、导出未保存内容与重试');
  const sharedUrl = page.url();
  const other = await page.context().newPage();
  await other.goto(sharedUrl);
  const otherName = other.getByRole('textbox', { name: '全名', exact: true });
  await otherName.waitFor();
  await page.getByRole('button', { name: '简历内容', exact: true }).click();
  await name.fill('标签 A 的草稿');
  await otherName.fill('标签 B 的更新');
  await other.getByRole('button', { name: '保存', exact: true }).click();
  const aDialog = page.getByRole('dialog', { name: '另一个标签页更新了简历', exact: true });
  const bDialog = other.getByRole('dialog', { name: '另一个标签页更新了简历', exact: true });
  await Promise.any([aDialog.waitFor({ state: 'visible', timeout: 10000 }), bDialog.waitFor({ state: 'visible', timeout: 10000 })]);
  const onA = await aDialog.isVisible();
  const conflicted = onA ? page : other;
  const dialog = onA ? aDialog : bDialog;
  await dialog.getByRole('button', { name: '保留我的修改为新简历', exact: true }).click();
  await conflicted.waitForFunction(oldUrl => window.location.href !== oldUrl, sharedUrl);
  const copyName = conflicted.getByRole('textbox', { name: '全名', exact: true });
  await copyName.waitFor();
  if (await copyName.inputValue() !== (onA ? '标签 A 的草稿' : '标签 B 的更新')) throw new Error('Conflict recovery lost the local changes');
  if (!onA) await page.goto(conflicted.url());
  await other.close();
  await page.reload();
  await name.waitFor();
  report.push('真实双标签冲突、另存副本与刷新恢复');
  return { passed: report, resolvedUrl: page.url() };
}
