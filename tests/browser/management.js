async (page) => {
  const report = [];
  await page.setViewportSize({ width: 1440, height: 900 });
  const originalUrl = page.url();
  const title = await page.getByRole('textbox', { name: '简历名称', exact: true }).inputValue();
  await page.getByRole('link', { name: '返回我的简历', exact: true }).click();
  await page.getByRole('button', { name: '更多操作 ' + title, exact: true }).click();
  await page.getByRole('menuitem', { name: '复制简历', exact: true }).click();
  const copyTitle = title + ' · 副本';
  await page.getByRole('link', { name: '编辑 ' + copyTitle, exact: true }).click();
  const name = page.getByRole('textbox', { name: '全名', exact: true });
  await name.fill('副本姓名');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.save-indicator.saved'));
  const original = await page.context().newPage();
  await original.goto(originalUrl);
  const originalName = original.getByRole('textbox', { name: '全名', exact: true });
  await originalName.waitFor();
  if (await originalName.inputValue() !== '林交互测试') throw new Error('Copy changed the original');
  await original.close();
  report.push('复制后独立编辑');
  const restore = async (reason) => {
    await page.getByRole('button', { name: '历史记录', exact: true }).click();
    const history = page.getByRole('dialog', { name: '历史记录', exact: true });
    await history.locator('.history-list').getByRole('button').filter({ hasText: reason }).first().click();
    await history.getByRole('button', { name: '恢复此版本', exact: true }).click();
    const confirm = page.getByRole('dialog', { name: '恢复这个历史版本？', exact: true });
    await confirm.getByRole('button', { name: '确认恢复', exact: true }).click();
    await confirm.waitFor({ state: 'hidden' });
    await history.getByRole('button', { name: '关闭对话框', exact: true }).click();
  };
  await restore('创建');
  if (await name.inputValue() !== '林交互测试') throw new Error('History restore did not apply');
  await restore('恢复前');
  if (await name.inputValue() !== '副本姓名') throw new Error('History roundtrip lost the original current value');
  report.push('历史恢复与恢复回来');
  await page.getByRole('link', { name: '返回我的简历', exact: true }).click();
  await page.getByRole('button', { name: '更多操作 ' + copyTitle, exact: true }).click();
  await page.getByRole('menuitem', { name: '移入回收站', exact: true }).click();
  await page.getByRole('link', { name: /^回收站/ }).click();
  await page.getByRole('button', { name: copyTitle + '回收站操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '恢复简历', exact: true }).click();
  await page.getByRole('link', { name: /^我的简历/ }).click();
  await page.getByRole('link', { name: '编辑 ' + copyTitle, exact: true }).waitFor();
  report.push('回收站恢复');
  await page.getByRole('button', { name: '导入简历', exact: true }).click();
  await page.getByLabel('选择导入文件', { exact: true }).setInputFiles('output/playwright/resume-backup.json');
  await page.getByRole('button', { name: '确认导入', exact: true }).click();
  await page.getByRole('textbox', { name: '全名', exact: true }).waitFor();
  if (page.url() === originalUrl || await page.getByRole('textbox', { name: '全名', exact: true }).inputValue() !== '林交互测试') throw new Error('Backup did not create an independent matching resume');
  if (await page.locator('.avatar-control img').count() !== 1) throw new Error('Backup lost its photo');
  report.push('JSON 备份导入与照片保留');
  await page.screenshot({ path: 'output/playwright/imported-editor.png', scale: 'css' });
  return { passed: report, importedUrl: page.url() };
}
