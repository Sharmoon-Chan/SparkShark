async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const pdfRequests = [], browserRequests = [];
  const pdfBlock = async route => { pdfRequests.push(route.request().url()); await route.abort(); };
  const fontBlock = async route => { browserRequests.push(route.request().url()); await route.abort(); };
  await page.context().route('**/fonts/compressed/**', pdfBlock);
  await page.context().route('**/pdf.worker*', pdfBlock);
  await page.context().route('**/fonts/browser/**', fontBlock);
  await page.bringToFront(); await page.reload();
  const ready = () => page.waitForFunction(() => document.querySelector('.html-preview-frame')?.contentDocument?.querySelector('#preview-pages[data-ready="true"]'), null, { timeout: 30000 });
  await ready();
  const title = page.getByRole('textbox', { name: '全名', exact: true });
  await title.fill('字体失败仍可编辑');
  await ready();
  assert(await page.frameLocator('.html-preview-frame').locator('#preview-source h1').textContent() === '字体失败仍可编辑', 'Content blocked by font failure');
  await page.getByRole('button', { name: '字体待重试', exact: true }).waitFor();
  await page.context().unroute('**/fonts/browser/**', fontBlock);
  await page.getByRole('button', { name: '字体待重试', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.html-preview-frame').contentDocument.querySelector('#preview-pages').dataset.fontState === 'ready', null, { timeout: 30000 });
  await page.evaluate(async () => {
    const { useApp } = await import('/src/app/store.ts');
    const { paginationFixtures } = await import('/tests/fixtures/pagination.ts');
    window.__originalPreviewResume = structuredClone(useApp.getState().current);
    const long = paginationFixtures().find(item => item.id === 'double-left-long-sidebar').resume;
    useApp.getState().update(next => { const id = next.id; Object.assign(next, long, { id }); });
  });
  await ready();
  await page.waitForFunction(() => Number(document.querySelector('.html-preview-frame').contentDocument.querySelector('#preview-pages').dataset.pageCount) >= 8);
  const originalDocument = await page.evaluate(() => {
    const d = document.querySelector('.html-preview-frame').contentDocument;
    window.__stableDoc = d;
    const scroll = document.querySelector('.html-preview-scroll'); scroll.scrollTop = 2500;
    return { pages: Number(d.querySelector('#preview-pages').dataset.pageCount), scroll: scroll.scrollTop };
  });
  await title.fill('滚动保持验证'); await ready();
  const after = await page.evaluate(() => ({ sameDocument: window.__stableDoc === document.querySelector('.html-preview-frame').contentDocument, scroll: document.querySelector('.html-preview-scroll').scrollTop }));
  assert(after.sameDocument, 'Iframe document recreated by typing');
  assert(Math.abs(after.scroll - originalDocument.scroll) < 120, 'Scroll jumped away during edit');
  await page.getByRole('combobox', { name: '预览缩放', exact: true }).selectOption('75');
  const revision = await page.evaluate(() => document.querySelector('.html-preview-frame').contentDocument.querySelector('#preview-pages').dataset.paginationRevision);
  await page.getByRole('combobox', { name: '预览缩放', exact: true }).selectOption('100');
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const revisionAfterZoom = await page.evaluate(() => document.querySelector('.html-preview-frame').contentDocument.querySelector('#preview-pages').dataset.paginationRevision);
  assert(revisionAfterZoom === revision, 'Zoom repaginated content');
  await page.getByRole('combobox', { name: '预览缩放', exact: true }).selectOption('fit');
  await page.locator('.html-preview-scroll').evaluate(element => { element.scrollTop = 1400; });
  await page.screenshot({ path: 'output/playwright/stage2-long-pages.png', scale: 'css' });
  await page.evaluate(async () => { const { useApp } = await import('/src/app/store.ts'); useApp.getState().update(next => Object.assign(next, window.__originalPreviewResume)); });
  await ready(); await title.fill('林示例'); await ready();
  await page.locator('.html-preview-scroll').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: 'output/playwright/stage2-desktop.png', scale: 'css' });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('button', { name: '预览', exact: true }).click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile horizontal overflow');
  await page.screenshot({ path: 'output/playwright/stage2-mobile.png', scale: 'css' });
  assert(pdfRequests.length === 0, 'Implicit PDF render during instant mode');
  await page.context().unroute('**/fonts/compressed/**', pdfBlock); await page.context().unroute('**/pdf.worker*', pdfBlock);
  return { fontFailureEditable: true, fontRetry: true, blockedFontRequests: browserRequests.length, stableDocument: after.sameDocument, scrollBefore: originalDocument.scroll, scrollAfter: after.scroll, pages: originalDocument.pages, zoomReusesPagination: true, pdfRequests: pdfRequests.length, mobileOverflow: false };
}
