async (page) => {
  const report = [];
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('button', { name: '导入简历', exact: true }).click();
  await page.getByLabel('选择导入文件', { exact: true }).setInputFiles('output/pdf/m0-example.pdf');
  await page.getByRole('heading', { name: '核对识别结果', exact: true }).waitFor({ timeout: 25000 });
  const dialog = page.getByRole('dialog', { name: '导入简历', exact: true });
  const name = dialog.getByRole('textbox', { name: '全名', exact: true });
  const extracted = { name: await name.inputValue(), phone: await dialog.getByRole('textbox', { name: '电话', exact: true }).inputValue(), email: await dialog.getByRole('textbox', { name: '邮箱', exact: true }).inputValue() };
  if (extracted.name !== '林示例' || extracted.phone !== '000-0000-0000' || extracted.email !== 'lin.demo@example.com') throw new Error('PDF basic mapping is wrong: ' + JSON.stringify(extracted));
  const work = dialog.locator('.mapping-row').filter({ has: page.getByRole('combobox', { name: '工作经历映射到模块', exact: true }) });
  await work.getByRole('button', { name: /核对 .* 条记录/ }).click();
  if (await work.getByRole('textbox', { name: '公司', exact: true }).first().inputValue() !== '示例科技公司') throw new Error('PDF work company not mapped');
  await dialog.getByRole('button', { name: '查看原 PDF', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.import-original-preview canvas')?.dataset.rendered === 'true');
  await page.screenshot({ path: 'output/playwright/pdf-import-review.png', scale: 'css' });
  await name.fill('PDF 导入示例');
  await dialog.getByRole('button', { name: '确认导入', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('textbox', { name: '全名', exact: true }).waitFor();
  if (await page.getByRole('textbox', { name: '全名', exact: true }).inputValue() !== 'PDF 导入示例') throw new Error('PDF import did not honor reviewed fields');
  await page.reload();
  await page.getByRole('textbox', { name: '全名', exact: true }).waitFor();
  if (await page.getByRole('textbox', { name: '全名', exact: true }).inputValue() !== 'PDF 导入示例') throw new Error('PDF import did not persist');
  report.push('实际 PDF 读取、分栏识别、字段核对、创建与刷新恢复');
  await page.getByRole('link', { name: '返回我的简历', exact: true }).click();
  await page.getByRole('button', { name: '导入简历', exact: true }).click();
  await page.getByLabel('选择导入文件', { exact: true }).setInputFiles('output/playwright/resume-export.pdf');
  await page.getByRole('heading', { name: '核对识别结果', exact: true }).waitFor({ timeout: 25000 });
  const photo = page.getByRole('switch', { name: '使用 PDF 中识别的照片', exact: true });
  await photo.waitFor();
  if (await photo.getAttribute('aria-checked') !== 'true') throw new Error('PDF photo was not detected');
  await page.getByRole('button', { name: '确认导入', exact: true }).click();
  await page.getByRole('textbox', { name: '全名', exact: true }).waitFor();
  await page.locator('.avatar-control img').waitFor();
  if (await page.locator('.avatar-control img').count() !== 1) throw new Error('PDF photo did not survive import');
  report.push('PDF 照片识别与导入');
  await page.getByRole('link', { name: '返回我的简历', exact: true }).click();
  await page.getByRole('button', { name: '导入简历', exact: true }).click();
  await page.getByLabel('选择导入文件', { exact: true }).setInputFiles('output/pdf/pdf-import-scan.pdf');
  await page.getByRole('alert').filter({ hasText: '没有读取到可编辑文字' }).waitFor({ timeout: 25000 });
  if (await page.getByRole('button', { name: '确认导入', exact: true }).isEnabled()) throw new Error('Scanned PDF enabled an empty import');
  report.push('扫描件明确提示且不会生成空简历');
  await page.getByLabel('选择导入文件', { exact: true }).setInputFiles('output/pdf/pdf-import-broken.pdf');
  await page.getByRole('alert').waitFor();
  if (await page.getByRole('button', { name: '确认导入', exact: true }).isEnabled()) throw new Error('Corrupt PDF enabled import');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  report.push('损坏 PDF 的失败状态和取消');
  return { passed: report, extractedBasics: extracted };
}
