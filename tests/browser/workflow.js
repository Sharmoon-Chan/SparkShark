async (page) => {
  const report = [];
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.reload();
  await page.getByRole('link', { name: '返回我的简历', exact: true }).click();
  await page.getByRole('button', { name: '新建简历', exact: true }).click();
  await page.getByRole('textbox', { name: '简历名称', exact: true }).fill('空白流程测试');
  await page.getByRole('button', { name: /^空白简历/ }).click();
  await page.getByRole('button', { name: '创建简历', exact: true }).click();
  const name = page.getByRole('textbox', { name: '全名', exact: true });
  await name.waitFor();
  if (await name.inputValue()) throw new Error('Blank creation has unexpected example content');
  await name.fill('林新建示例');
  await page.getByRole('textbox', { name: '邮箱', exact: true }).fill('new.example@example.com');
  const work = page.locator('#section-work');
  await work.getByRole('button', { name: '新增工作', exact: true }).click();
  await work.getByRole('textbox', { name: '公司', exact: true }).fill('新的虚构公司');
  await work.getByRole('textbox', { name: '职位', exact: true }).fill('前端工程师');
  await work.getByRole('textbox', { name: '详情', exact: true }).fill('新增工作详情，用于验证条目输入与保存。');
  await page.getByRole('button', { name: '新增自定义模块', exact: true }).click();
  await page.getByRole('textbox', { name: '模块名称', exact: true }).fill('活动经历');
  await page.getByRole('button', { name: '创建模块', exact: true }).click();
  const custom = page.locator('[data-section-id]').filter({ has: page.getByRole('heading', { name: '活动经历', exact: true }) });
  await custom.getByRole('button', { name: '新增活动', exact: true }).click();
  await custom.getByRole('textbox', { name: '名称', exact: true }).fill('校园活动示例');
  await custom.getByRole('textbox', { name: '详情', exact: true }).fill('自定义内容完整保留。');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.save-indicator.saved'));
  await page.reload();
  await name.waitFor();
  if (await name.inputValue() !== '林新建示例') throw new Error('Blank resume did not persist');
  if (await page.getByRole('heading', { name: '活动经历', exact: true }).count() !== 1) throw new Error('Custom section lost after reload');
  report.push('空白创建、工作条目、自定义模块与刷新恢复');
  const summary = page.getByRole('textbox', { name: '个人总结', exact: true });
  await summary.fill('简历分页测试，所有内容均为虚构。'.repeat(80));
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.preview-updating') && Number(document.querySelector('.preview-heading')?.textContent.match(/(\d+) 页/)?.[1]) >= 2, null, { timeout: 25000 });
  await page.getByRole('button', { name: '尝试一页排版', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.preview-updating') && document.querySelector('.preview-heading')?.textContent.includes('1 页') && document.querySelector('[aria-label="还原一页排版前的参数"]'), null, { timeout: 25000 });
  if ((await summary.innerText()).length < 1200) throw new Error('Fit one page shortened content');
  await page.getByRole('button', { name: '还原一页排版前的参数', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.preview-updating') && Number(document.querySelector('.preview-heading')?.textContent.match(/(\d+) 页/)?.[1]) >= 2, null, { timeout: 25000 });
  report.push('一页排版成功与参数还原，正文保留');
  await page.getByRole('button', { name: '导出与备份', exact: true }).click();
  const zipEvent = page.waitForEvent('download');
  await page.locator('.panel-content').getByRole('button', { name: '下载图片', exact: true }).click();
  const zip = await zipEvent;
  if (!zip.suggestedFilename().endsWith('.zip')) throw new Error('Multi-page images were not packaged');
  await zip.saveAs('output/playwright/multipage-images.zip');
  report.push('多页 PNG 的 ZIP 下载');
  await page.getByRole('link', { name: '返回我的简历', exact: true }).click();
  await page.getByRole('button', { name: '导入简历', exact: true }).click();
  await page.getByRole('button', { name: '文本 / Markdown', exact: true }).click();
  await page.getByRole('textbox', { name: '粘贴文本', exact: true }).fill('# 个人总结\n\nMarkdown 导入验证。\n\n# 校园活动\n\n组织活动，日期 2024—至今，原文应保留。');
  await page.getByRole('button', { name: '预览解析结果', exact: true }).click();
  const mapping = page.getByRole('combobox', { name: '校园活动映射到模块', exact: true });
  if (await mapping.inputValue() !== 'custom') throw new Error('Unknown heading was not preserved as custom');
  await page.getByRole('button', { name: '确认导入', exact: true }).click();
  await page.getByRole('heading', { name: '校园活动', exact: true }).waitFor();
  report.push('文本导入、人工映射与未知模块保留');
  await page.screenshot({ path: 'output/playwright/text-import-editor.png', scale: 'css' });
  return { passed: report, finalUrl: page.url() };
}
